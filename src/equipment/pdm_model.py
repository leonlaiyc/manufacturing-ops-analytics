"""
Gradient-boosting health model with SHAP explanations (M8 Stage C).

FRAMING (repeated from ``sensor_sim.py``; read that module's docstring
first): the channels this model is trained on are self-generated by this
project, with a documented rule wiring exactly two channels to a degradation
ramp. Nothing here demonstrates predictive maintenance (PdM) on a real fab.
Every metric in this module is a DETECTION-QUALITY score against the KNOWN
synthetic ground truth attached at generation time - ROC AUC against the
``degraded`` label we ourselves assigned, SHAP importance against the two
channels we ourselves wired, detection delay/false-alarm rate against the
onset day we ourselves drew. Read every AUC, delay, and ranking in this
module as "did the model recover the rule we wrote", never as "how well
would this work on a real tool".

Why episode-level train/test split, not day-level
------------------------------------------------------
Rolling-window features (see ``build_features``) make consecutive days of
the SAME tool-episode highly correlated: day t's rolling mean/std/slope
shares most of its input window with day t+1's. A day-level random split
would put near-duplicate rows (overlapping windows of the same ramp) on both
sides of the train/test boundary, so the model could "test well" simply by
memorizing the shape of a ramp it partially saw in training - leakage, not
generalization, and it would inflate AUC in a way that has nothing to do
with detection quality. Splitting whole EPISODES (independent seeds, onset
days, and severities - see ``sensor_sim.make_episodes``) into train vs test
means the test episodes' onset day, severity, and noise realization are
never seen in any form during training, so held-out AUC reflects whether the
model recovered the GENERAL rule (two wired channels rising with a ramp)
rather than one episode's particular draw.

Causality of features (documented, checked in GATE 2 of pdm_check.py)
--------------------------------------------------------------------------
``build_features`` computes, for day t, a trailing window over
``[t - window + 1, t]`` ONLY - it never reads day t+1 or later. This is
checked structurally (GATE 2): recomputing features after overwriting every
row's channel values on days AFTER that row's own day with garbage produces
BYTE-IDENTICAL feature rows, proving no future day's value can leak into
day t's features no matter how it is corrupted.
"""

